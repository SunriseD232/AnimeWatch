import { NextResponse } from 'next/server';

export const dynamic = 'force-dynamic';

/**
 * Часы сервера для совместного просмотра. Участники комнаты договариваются о
 * позиции видео в виде «на момент T было t секунд» (см. WatchPartyProvider),
 * и T должно значить одно и то же на всех устройствах. Системные часы
 * телефонов и компьютеров расходятся на секунды — этого хватило бы, чтобы
 * плееры дёргались перемотками друг за другом. Клиент меряет смещение своих
 * часов от этих, учитывая время ответа, и дальше считает в серверном времени.
 */
export function GET() {
  return NextResponse.json({ now: Date.now() }, { headers: { 'Cache-Control': 'no-store' } });
}
