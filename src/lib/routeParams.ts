/**
 * Динамический сегмент адреса как есть — без процентного кодирования.
 *
 * Next 14 отдаёт params ещё закодированными: для /manga/%3C29.04.2026%3Eeleceed_
 * params.dir === '%3C29.04.2026%3Eeleceed_'. Код дальше кодирует слаг сам
 * (encodeURIComponent в запросе к Remanga/Renovels), и выходило двойное
 * кодирование — %253C, источник отвечал 404, карточка не открывалась. У
 * обычных слагов (латиница, «_», «-») кодировать нечего, поэтому ломались
 * только такие, как «<29.04.2026>eleceed_» — 86 тайтлов манги на 23.10.2026.
 *
 * Битая последовательность (одиночный «%») — вернуть как есть, а не падать.
 */
export function decodeSegment(value: string): string {
  try {
    return decodeURIComponent(value);
  } catch {
    return value;
  }
}
