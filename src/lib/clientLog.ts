'use client';

/**
 * Отправляет одно диагностическое событие на /api/client-log — оттуда оно
 * попадает в тот же серверный console.log, что читается через `pm2 logs
 * mediawatch-web` (см. комментарий в api/client-log/route.ts). Смысл — не
 * "аналитика", а восстановление конкретной ленты действий пользователя
 * постфактум, когда он сообщает о проблеме (какую вкладку/озвучку выбрал,
 * когда сорвался retry, на каком событии hls.js упал и т.п.) — то, что
 * раньше было видно только в консоли ЕГО браузера и терялось насовсем.
 *
 * Никогда не бросает и не блокирует UI — logEvent НЕ должен становиться
 * ещё одним источником сбоя в месте, где его вызвали (тот же принцип, что
 * уже применяется к save()/fetch('/api/progress', ...) по всему плееру).
 * keepalive: true — тот же приём, что у /api/progress: событие должно
 * дойти, даже если вызвано прямо перед уходом со страницы/сменой серии.
 */
export function logEvent(event: string, data?: Record<string, unknown>): void {
  try {
    fetch('/api/client-log', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ event, data }),
      keepalive: true,
    }).catch(() => {});
  } catch {
    // fetch сам может синхронно бросить в редких средах (например, если
    // keepalive-тело превышает лимит браузера) — глотаем и здесь тоже.
  }
}
