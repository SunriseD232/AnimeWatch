-- MediaWatch — миграция 0062: настройки читалки манги в профиле
--
-- ЗАЧЕМ. У читалки появились настройки «как на MangaLib»: режим (по
-- странице / лента / полоса), направление, зоны нажатия, вписывание
-- картинки, яркость и т. д. (lib/mangaReaderSettings.ts). Хранить их только
-- в браузере — значит настраивать заново на каждом устройстве, поэтому они
-- живут в profiles рядом с другими личными настройками интерфейса (0038,
-- 0045). Копия в localStorage остаётся — для мгновенного применения и для
-- чтения без входа.
--
-- Один jsonb, а не колонка на настройку: их полтора десятка, они будут
-- добавляться, и проверяет их код (normalizeReaderSettings) — неизвестное
-- поле или кривое значение там превращаются в значение по умолчанию. NULL —
-- «ещё не настраивал»: берётся копия из браузера или значения по умолчанию.
--
-- Пишет только /api/profile от service_role (у profiles нет политик записи
-- для authenticated, см. 0036), поэтому политики здесь не меняются.

alter table profiles
  add column if not exists manga_reader jsonb;

comment on column profiles.manga_reader is
  'Настройки читалки манги (lib/mangaReaderSettings.ts). NULL — не настраивались.';
