-- MediaWatch — миграция 0045: общий поиск по аниме и кино
--
-- ЗАЧЕМ. Раздел поиска сейчас определяется тем, где человек находится: под
-- /cinema ищем кино, везде остальное — аниме (см. SearchBox.tsx). Тому, кто
-- держит оба раздела как одну библиотеку, это лишний шаг: он вводит
-- название и не находит его, потому что стоял не в том разделе.
--
-- Настройка личная и по умолчанию ВЫКЛЮЧЕНА: прежнее поведение никому молча
-- не меняем. Включённая — поиск ищет сразу по обоим разделам, и подсказки, и
-- страница результатов.
--
-- Живёт в profiles рядом с настройками плеера (0038/0039): это такая же
-- личная настройка интерфейса, отдельной таблицы ей не надо.

alter table profiles
  add column if not exists unified_search boolean not null default false;

comment on column profiles.unified_search is
  'Искать сразу по аниме и кино, не оглядываясь на текущий раздел сайта.';
