-- MediaWatch — миграция 0040: жанры каталога кино из выгрузки IMDb
--
-- ЗАЧЕМ. У Videoseed жанры есть только у фильмов. Сериалам, мультфильмам и
-- мультсериалам он в genre_ids/genres_id кладёт ОДИН лишь маркер типа
-- («Сериалы»=20, «Мультфильмы»=21, «Мультсериалы»=22) и ничего больше —
-- проверено на живом API: list=serial отдаёт genre = "Сериалы", genres_id =
-- "20" на каждой записи. Посчитано по индексу на 18.09.2026: у 18 748
-- сериалов, 4 548 мультфильмов и 238 мультсериалов настоящих жанров РОВНО
-- НОЛЬ, тогда как у 70 198 фильмов их в среднем 2,19.
--
-- Отсюда обе жалобы: у «Во все тяжкие» в карточке пусто (в индексе {20}), а
-- фильтр «Тип: Сериал» + «Жанр: Драма» не находит ничего — потому что такого
-- сочетания в данных не существует. Фильтровать по жанру на стороне
-- Videoseed тоже нельзя: genre_id= он молча игнорирует (см. 0027).
--
-- ОТКУДА БЕРЁМ. Официальная выгрузка IMDb title.basics.tsv.gz (227 МБ,
-- обновляется ежедневно, без ключа и лимитов). Связываемся по imdb_id,
-- который у нас уже есть от Videoseed. Замерено на проде 18.09.2026: полный
-- проход по 12,8 млн строк вместе со скачиванием занял 20 секунд и нашёл
-- 18 339 из 18 410 наших сериалов и мультфильмов (99,6%), у всех найденных
-- жанры заполнены.
--
-- Почему не TMDB, хотя туда мы уже ходим за рейтингами: у TMDB для сериалов
-- отдельный, более грубый словарь жанров («НФ и Фэнтези», «Боевик и
-- Приключения» одним пунктом), и в нём нет ни триллера, ни ужасов, ни
-- биографии, ни спорта — то есть часть наших фильтров осталась бы пустой.
-- Плюс это 19 тысяч запросов через VLESS-туннель против одного файла.
--
-- КАК ЖИВЁТ. Той же схемой, что cinema_ratings: отдельная долгоживущая
-- таблица, которая ПЕРЕЖИВАЕТ ночную перестройку каталога, и свой крон. В
-- выдачу жанры попадают следующей перестройкой — она сливает их с жанрами
-- Videoseed в cinema_index.genre_ids.

create table if not exists cinema_imdb_genres (
  imdb_id text primary key,
  -- Идентификаторы НАШЕГО справочника cinema_genres (Боевик=2, Драма=8…),
  -- уже переведённые из английских названий IMDb — см. IMDB_GENRE_MAP в
  -- lib/cinemaGenres.ts. Храним в готовом виде, чтобы перестройка каталога
  -- не занималась переводом на 93 тысячах строк.
  --
  -- Пустой массив — законное значение: «в выгрузке тайтл есть, но ни один
  -- его жанр в наш справочник не переводится» (например, только Talk-Show).
  -- Так он не будет вечно считаться непроверенным.
  genre_ids smallint[] not null default '{}',
  updated_at timestamptz not null default now()
);

-- Отдельно про жанры в состоянии: у них свой график и свой исход, путать их
-- с перестройкой каталога и с рейтингами нельзя — иначе неудача одного
-- маскирует другое (та же логика, что у ratings_* в 0027).
alter table cinema_index_state add column if not exists genres_run_started_at timestamptz;
alter table cinema_index_state add column if not exists genres_run_finished_at timestamptz;
alter table cinema_index_state add column if not exists genres_matched integer not null default 0;
alter table cinema_index_state add column if not exists genres_error text;

-- Доступы — как у остальных таблиц каталога (0027): данные публичные,
-- одинаковые для всех, RLS включаем ради явной политики чтения.
alter table cinema_imdb_genres enable row level security;

drop policy if exists "anyone can read cinema imdb genres" on cinema_imdb_genres;
create policy "anyone can read cinema imdb genres" on cinema_imdb_genres for select using (true);

-- Явный грант — без него RLS policy не работает: Postgres сначала проверяет
-- табличные права. Та же грабля, что в 0020/0021/0024/0025/0027.
grant select on cinema_imdb_genres to authenticated, anon;

-- Пишет только крон, он ходит под service_role (обходит RLS).
