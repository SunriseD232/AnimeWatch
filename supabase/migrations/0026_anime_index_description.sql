-- MediaWatch — миграция 0026: описание тайтла в индексе каталога
-- Применить через Supabase SQL Editor (или psql внутри контейнера
-- supabase-db, см. README).
--
-- Нужно списочному виду каталога («Вид → Список»): там под названием идёт
-- краткое описание. Брать его в рантайме у Shikimori значило бы вернуть
-- ровно ту зависимость, ради ухода от которой индекс и заводили — плюс
-- лишний запрос на каждую отрисовку страницы.
--
-- Место: ~800 символов на тайтл, на 24 тысячи это около 20 МБ. Отдельной
-- таблицей не выносим: описание читается ровно тогда же, когда и остальная
-- строка, и join ради экономии на плитках, где оно не нужно, дал бы больше
-- сложности, чем пользы — в плиточном виде колонка просто не запрашивается
-- (см. SELECT_COLUMNS в lib/animeIndexQuery.ts).
--
-- Колонка nullable и без бэкфилла: старые партии останутся без описаний,
-- новые получат их при ближайшей полной перезакачке (она и так суточная).
-- До этого списочный вид просто не покажет текст — не ошибка, а пустое
-- место.

alter table anime_index add column if not exists description text;
