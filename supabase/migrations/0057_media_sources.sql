-- MediaWatch — миграция 0057: слой источников для манги/ранобэ/книг
--
-- ЧТО ДОБАВЛЯЕТ
--   1. title_sources    — где тайтл лежит в каждом источнике (корень тайтла).
--   2. canonical_chapters — каноническое оглавление, общее для всех источников.
--   3. chapter_sources  — доступность канонической главы в источнике.
--   4. source_health    — здоровье источников + kill-switch.
--   5. source_link_state — курсор chunked-крона маппинга.
--
-- ПОЧЕМУ ОТДЕЛЬНЫЕ ТАБЛИЦЫ
--   Один тайтл может читаться из Remanga, MangaDex, SelfManga и т. д.
--   У источников разная нумерация глав, поэтому прогресс нельзя ключевать
--   номером главы источника. Каноническая ось (idx) стабильна для тайтла,
--   а chapter_sources отвечает, где эта глава бесплатна.
--
-- ВАЖНО ПРО КЛЮЧ
--   `title_key` — это НЕ Shikimori id, а id источника-каталога:
--     manga  -> id Remanga
--     ranobe -> id Renovels
--     book   -> id Флибусты
--   Он совпадает со значением shikimori_id в watch_progress/user_list/
--   watched_episodes для соответствующего content_type.
--
-- Применять вручную через Supabase SQL Editor после 0053–0056.

-- ─────────────────────────────────────────────────────────────
-- 1. Источники тайтла
-- ─────────────────────────────────────────────────────────────
create table if not exists title_sources (
  id bigint generated by default as identity primary key,

  content_type text not null check (content_type in ('manga', 'ranobe', 'book')),
  -- id тайтла у источника-каталога (= shikimori_id прогресса).
  title_key bigint not null,
  -- remanga | mangadex | mangalib | selfmanga | mintmanga | yai | renovels | flibusta
  source text not null,
  -- dir / manga uuid / slug / book id.
  external_id text not null,
  external_url text,
  -- Вариант внутри источника: том Флибусты, язык/группа MangaDex, издание.
  variant text not null default 'default',

  title text,
  chapters_count integer,
  language text,
  -- Уверенность маппинга 0..1. Ниже порога источник не показывается.
  confidence real not null default 1,
  is_active boolean not null default true,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  unique (content_type, title_key, source, variant)
);

create index if not exists title_sources_lookup_idx
  on title_sources (content_type, title_key)
  where is_active;

create index if not exists title_sources_external_idx
  on title_sources (source, external_id);

-- ─────────────────────────────────────────────────────────────
-- 2. Каноническая глава
-- ─────────────────────────────────────────────────────────────
create table if not exists canonical_chapters (
  content_type text not null check (content_type in ('manga', 'ranobe', 'book')),
  title_key bigint not null,
  -- Порядковый номер 1..N. Уходит в watch_progress.episode.
  idx integer not null,
  -- Номер главы у источника: 21.2 (может быть дробным).
  chapter_no numeric,
  -- Том, если источник его различает: «том 2, глава 1» ≠ «том 1, глава 1».
  tome smallint,
  label text not null,

  primary key (content_type, title_key, idx)
);

create index if not exists canonical_chapters_lookup_idx
  on canonical_chapters (content_type, title_key, idx);

-- ─────────────────────────────────────────────────────────────
-- 3. Где каноническая глава доступна
-- ─────────────────────────────────────────────────────────────
create table if not exists chapter_sources (
  content_type text not null check (content_type in ('manga', 'ranobe', 'book')),
  title_key bigint not null,
  idx integer not null,
  source text not null,
  variant text not null default 'default',
  -- int / uuid / slug у источника.
  source_chapter_key text not null,

  is_paid boolean not null default false,
  is_free_today boolean not null default false,
  pages_count integer,

  primary key (content_type, title_key, idx, source, variant),
  unique (content_type, title_key, source, variant, source_chapter_key)
);

create index if not exists chapter_sources_lookup_idx
  on chapter_sources (content_type, title_key, idx);

-- ─────────────────────────────────────────────────────────────
-- 4. Здоровье источников + kill-switch
-- ─────────────────────────────────────────────────────────────
create table if not exists source_health (
  source text primary key,
  enabled boolean not null default true,
  last_ok_at timestamptz,
  last_error text,
  errors_24h integer not null default 0,
  latency_ms integer,
  meta jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

-- ─────────────────────────────────────────────────────────────
-- 5. Курсор chunked-крона маппинга
-- ─────────────────────────────────────────────────────────────
create table if not exists source_link_state (
  -- Отдельный курсор на каждую джобу: 'manga' | 'ranobe'.
  job text primary key,
  content_type text not null,
  last_cursor bigint not null default 0,
  titles_total integer not null default 0,
  titles_done integer not null default 0,
  last_run_started_at timestamptz,
  last_run_finished_at timestamptz,
  last_error text
);

insert into source_link_state (job, content_type) values
  ('manga', 'manga'),
  ('ranobe', 'ranobe')
on conflict (job) do nothing;

-- ─────────────────────────────────────────────────────────────
-- 6. Доступы
-- ─────────────────────────────────────────────────────────────
alter table title_sources enable row level security;
alter table canonical_chapters enable row level security;
alter table chapter_sources enable row level security;
alter table source_health enable row level security;
alter table source_link_state enable row level security;

drop policy if exists "anyone can read title_sources" on title_sources;
drop policy if exists "anyone can read canonical_chapters" on canonical_chapters;
drop policy if exists "anyone can read chapter_sources" on chapter_sources;
drop policy if exists "authenticated can read source_health" on source_health;
drop policy if exists "authenticated can read source_link_state" on source_link_state;

create policy "anyone can read title_sources"
  on title_sources for select using (true);
create policy "anyone can read canonical_chapters"
  on canonical_chapters for select using (true);
create policy "anyone can read chapter_sources"
  on chapter_sources for select using (true);
create policy "authenticated can read source_health"
  on source_health for select to authenticated using (true);
create policy "authenticated can read source_link_state"
  on source_link_state for select to authenticated using (true);

-- Пишет только service_role (кроны и серверный резолвер). Политик INSERT/
-- UPDATE для обычных пользователей нет намеренно.
grant select on title_sources to authenticated, anon;
grant select on canonical_chapters to authenticated, anon;
grant select on chapter_sources to authenticated, anon;
grant select on source_health to authenticated;
grant select on source_link_state to authenticated;
