-- MediaWatch — миграция 0047: разовая подсказка «загляните в профиль»
-- Применить через Supabase SQL Editor.
--
-- Подсказка (components/ProfileHint.tsx) показывается ОДИН раз на аккаунт, а
-- не на устройство: закрыл на телефоне — на компьютере её уже не будет.
-- Поэтому флаг в БД, а не только в localStorage (там он лишь зеркало, чтобы
-- подсказка пропала сразу, не дожидаясь ответа сервера).
--
-- По умолчанию false: подсказку увидят и новые, и уже зарегистрированные
-- пользователи — для них в профиле как раз появились оформление и фон.
-- Живёт в profiles рядом с другими личными флагами интерфейса (0045).

alter table profiles
  add column if not exists profile_hint_seen boolean not null default false;

comment on column profiles.profile_hint_seen is
  'Пользователь уже видел и закрыл подсказку «загляните в профиль».';
